// ---------------------------------------------------------------------------
// Persistência local (localStorage) para favoritos do cidadão
// ---------------------------------------------------------------------------

function chaveFavoritos(idUsuario) {
  return `citizenlife:educacao:favoritos:${idUsuario ?? "visitante"}`;
}

export function lerFavoritosEducacao(idUsuario) {
  try {
    const bruto = localStorage.getItem(chaveFavoritos(idUsuario));
    const lista = bruto ? JSON.parse(bruto) : [];
    return Array.isArray(lista) ? lista : [];
  } catch {
    return [];
  }
}

export function salvarFavoritosEducacao(idUsuario, ids) {
  try {
    localStorage.setItem(chaveFavoritos(idUsuario), JSON.stringify(ids));
  } catch {
    // Ignora se o navegador bloquear o localStorage
  }
}

export function alternarFavoritoEducacao(idUsuario, idItem) {
  const atuais = lerFavoritosEducacao(idUsuario);
  const existe = atuais.includes(idItem);
  const proximos = existe ? atuais.filter((id) => id !== idItem) : [...atuais, idItem];
  salvarFavoritosEducacao(idUsuario, proximos);
  return { salvos: proximos, adicionado: !existe };
}
